"""Embed Source/Core/Themes/builtin-themes.toml as a C string in a generated .cpp.

Mirrors the Unifont codegen pattern: invoked from CMake (add_custom_command)
and from Scripts/run-tests.sh so the built-in themes have one source of truth
(the TOML) that ships compiled into the binary — no runtime file dependency.

Usage: embed-builtin-themes.py <builtin-themes.toml> <out.cpp>
"""
import sys

toml_path, out_path = sys.argv[1], sys.argv[2]
text = open(toml_path, "r", encoding="utf-8").read()

# Emit as a raw string literal with an exotic delimiter so no TOML content can
# terminate it early, and any byte (incl. UTF-8 theme names) survives verbatim
# without char-narrowing under -Werror.
DELIM = "UBTHEMESEOF"
assert (")" + DELIM + '"') not in text, "delimiter collides with TOML content"

out = f"""// Generated by Scripts/embed-builtin-themes.py from
// Source/Core/Themes/builtin-themes.toml — DO NOT EDIT. Regenerated at build time.
#include "Core/Themes/BuiltinThemesData.h"

namespace Ubiquitty {{
namespace Themes {{

    const char builtinThemesTOML[] = R"{DELIM}(
{text}){DELIM}";

    const unsigned builtinThemesTOMLLength = sizeof(builtinThemesTOML) - 1;

}} // namespace Themes
}} // namespace Ubiquitty
"""
open(out_path, "w", encoding="utf-8").write(out)
