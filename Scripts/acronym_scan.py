"""acronym_scan — the whole-tree half of check-acronyms.

Reads repository-relative paths from argv or stdin and prints, for each line
tripping a naming rule:

    path:lineno: naming: RULE
      > the stripped line

Exit 1 when any file had a hit, 0 when none did.

It runs across the cores, and a literal first pass rejects most lines before
any rule is asked.

Bytes, not text. The perl this replaces read bytes and matched with perl's
default \\b, which is ASCII; the files are decoded latin-1 here so every byte
round-trips, the rules carry re.ASCII, and output is written back as bytes. A
utf-8 decode would move a word boundary next to a non-ASCII letter and change
what the gate reports.
"""

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from acronym_rules import RULES, may_trip

# A generated file declares itself in its header, and a naming violation there
# is not fixable in that file — the generator emitted the name, and editing the
# output is what its own banner forbids. Reporting one would be an error nobody
# can act on where it is reported.
#
# It is also where the time goes: UnifontData.cpp is a large table of hex,
# and it holds no identifiers of ours at all.
GENERATED = re.compile(r"DO NOT EDIT|\bgenerated by\b", re.IGNORECASE | re.ASCII)
GENERATED_HEADER_LINES = 40

FULL_LINE_COMMENT = re.compile(r"^\s*//", re.ASCII)
BLOCK_COMMENT_BODY = re.compile(r"^\s*\*[^/]", re.ASCII)
PREPROCESSOR = re.compile(r"^\s*#\s*(?:include|define|ifdef|ifndef|endif|pragma|if\b)",
                          re.ASCII)
COMMENT_TAIL = re.compile(r"//.*$", re.ASCII)
STRING_LITERAL = re.compile(r'"(?:[^"\\]|\\.)*"', re.ASCII)


def is_generated(text):
    """Whether a file's first lines declare it machine-written."""
    head = text.split("\n", GENERATED_HEADER_LINES)[:GENERATED_HEADER_LINES]
    return any(GENERATED.search(line) for line in head)


def read_head(handle, lines):
    """The first `lines` lines of an open binary file, and no more.

    The banner that answers `is_generated` is in the first few lines, so a file
    that turns out to be generated should never have been read past them.
    Reading in blocks rather than a fixed count of bytes keeps the answer the
    same as reading the whole file would give: a banner sitting behind one very
    long line is still found, where a byte budget would run out before it.

    - Parameters:
      - handle: A file open in binary mode, positioned at the start.
      - lines: How many lines the caller needs.
    - Returns: The bytes read, which hold at least that many lines or the whole
      file, whichever is shorter.
    """
    blocks = []
    seen = 0
    while seen < lines:
        block = handle.read(65536)
        if not block:
            break
        blocks.append(block)
        seen += block.count(b"\n")
    return b"".join(blocks)


def findings(relative, text):
    """Every rule each line of one file trips, in the report's own shape."""
    out = []
    for number, raw in enumerate(text.split("\n"), start=1):
        # skip full-line comments, block-comment body lines, and preprocessor
        if FULL_LINE_COMMENT.match(raw) or BLOCK_COMMENT_BODY.match(raw):
            continue
        if PREPROCESSOR.match(raw):
            continue
        line = raw.rstrip("\r")
        # strip inline // comment tails before identifier checks
        line = COMMENT_TAIL.sub("", line)
        # strip double-quoted string-literal contents — naming rules govern code
        # identifiers, not spec tokens that legitimately appear in string data
        # (RTF/HTML control words, escape and format sequences).
        line = STRING_LITERAL.sub("", line)
        # One pass over the union of every rule before any rule is asked.
        # Almost no line trips anything, and asking ninety patterns to prove
        # that costs the whole scan.
        if not may_trip(line):
            continue
        for message, trips in RULES:
            if trips(line):
                # Two encodings on one line, which is what perl emitted: the
                # rule's name is its own source file's UTF-8, and the source
                # line is the bytes that were read, put back exactly. Encoding
                # both one way either mangles a non-ASCII source line or refuses
                # to write the arrow in a rule's own name.
                out.append(b"%s:%d: naming: %s\n  > %s"
                           % (relative.encode("utf-8"), number,
                              message.encode("utf-8"), line.encode("latin-1")))
    return out


def scan(paths, root):
    """Findings across the corpus, and how many files carried one."""
    report = []
    filesWithHits = 0
    for relative in paths:
        path = relative if relative.startswith("/") else os.path.join(root, relative)
        if not os.path.isfile(path):
            continue
        try:
            with open(path, "rb") as handle:
                # The generated check decides on the banner, so the rest of the
                # file is read only once it is known to be worth reading.
                # UnifontData.cpp is a large table of hex holding no
                # identifiers of ours, and nothing needs to read past its
                # banner to know it.
                head = read_head(handle, GENERATED_HEADER_LINES)
                if is_generated(head.decode("latin-1")):
                    continue
                text = (head + handle.read()).decode("latin-1")
        except OSError:
            continue
        hits = findings(relative, text)
        if hits:
            report.extend(hits)
            filesWithHits += 1
    return report, filesWithHits


def _chunk(work):
    paths, root = work
    return scan(paths, root)


def scan_parallel(paths, root):
    """The same scan, spread over the cores.

    The work is regex over the whole tree, it divides by file with nothing
    shared, and the perl this replaces already ran several processes for
    exactly that reason. Below the threshold the pool's own setup costs more
    than it saves and the serial path runs instead.
    """
    workers = min(os.cpu_count() or 1, 8)
    if workers < 2 or len(paths) < 200:
        return scan(paths, root)
    import concurrent.futures
    size = (len(paths) + workers - 1) // workers
    chunks = [(paths[at:at + size], root) for at in range(0, len(paths), size)]
    report = []
    filesWithHits = 0
    with concurrent.futures.ProcessPoolExecutor(max_workers=workers) as pool:
        # map, not as_completed: the report's order is what a reader diffs
        # between runs, and a pool returns whichever chunk finished first.
        for chunkReport, chunkFiles in pool.map(_chunk, chunks):
            report.extend(chunkReport)
            filesWithHits += chunkFiles
    return report, filesWithHits


def main(argv):
    root = os.environ.get("UBQ_ACRONYMS_ROOT", ".")
    paths = argv if argv else [line.rstrip("\n") for line in sys.stdin]
    paths = [path for path in paths if path]
    report, filesWithHits = scan_parallel(paths, root)
    if report:
        sys.stdout.buffer.write(b"\n".join(report) + b"\n")
    return 1 if filesWithHits else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
