#
# Scripts/gen-unifont.py — bake GNU Unifont (.hex, BMP plane) into a compressed
# C++ blob: Source/Core/Rendering/UnifontData.{h,cpp}. Run manually; the generated
# files are checked in so a clean build needs no Python and no font at runtime.
#
#   ./Scripts/gen-unifont.py path/to/unifont_all-<version>.hex[.gz] [--version <version>]
#
# The input is a release's unifont_all-<version>.hex, from
# https://ftp.gnu.org/gnu/unifont/unifont-<version>/ (compressed there; either
# form is read). The version comes from that file name unless --version names
# it. Both the version and the SHA-256 of the uncompressed .hex are written into
# the generated header, so the checked-in blob names the release it was baked
# from and the exact input, and Docs/third-party-inventory.json pins the same.
#
# Font: GNU Unifont, used under the SIL Open Font License 1.1 (see
# Source/Core/Rendering/UnifontLICENSE.txt). The inflated blob is a stream of
# records sorted by code point: [u16 LE codePoint][u8 width(8|16)][bitmap],
# bitmap = (width/8 * 16) bytes, 1bpp row-major MSB-first.
#
import argparse
import gzip
import hashlib
import os
import re
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Source", "Core", "Rendering")
RELEASE_FILE = re.compile(r"^unifont_all-(\d+\.\d+\.\d+)\.hex(?:\.gz)?$")
# Each release's copyright statement: the COPYRIGHT its font/Makefile writes
# into every font it builds. The .hex carries none, so a release baked here
# needs its statement added, and one that is missing stops the script rather
# than baking a blob under another release's names.
COPYRIGHT = {
    "17.0.04": "Copyright (C) 1998-2026 Roman Czyborra, Paul Hardy, Qianqian Fang, Andrew Miller, Johnnie Weaver, "
               "David Corbett, \u00c6lla Chiana Moskopp, Rebecca Bettencourt, Minseo Lee, Ho-Seok Ee, et al.",
}

parser = argparse.ArgumentParser(description="Bake a GNU Unifont release's BMP glyphs into UnifontData.{h,cpp}.")
parser.add_argument("hex", help="unifont_all-<version>.hex or .hex.gz from a GNU Unifont release")
parser.add_argument("--version", help="the release, where the file name does not carry it")
arguments = parser.parse_args()

version = arguments.version
if not version:
    match = RELEASE_FILE.match(os.path.basename(arguments.hex))
    if not match:
        sys.exit("gen-unifont: the input is not named unifont_all-<version>.hex; pass --version")
    version = match.group(1)
if version not in COPYRIGHT:
    sys.exit("gen-unifont: no copyright statement recorded for Unifont %s; add the release's "
             "font/Makefile COPYRIGHT to COPYRIGHT" % version)

opener = gzip.open if arguments.hex.endswith(".gz") else open
with opener(arguments.hex, "rb") as handle:
    text = handle.read()
inputDigest = hashlib.sha256(text).hexdigest()
inputName = re.sub(r"\.gz$", "", os.path.basename(arguments.hex))

glyphs = []  # (codePoint, width, bitmap-bytes)
for line in text.decode("ascii").splitlines():
    line = line.strip()
    if not line or ":" not in line:
        continue
    key, bits = line.split(":", 1)
    codePoint = int(key, 16)
    if codePoint >= 0x10000:  # BMP plane only
        continue
    width = 8 if len(bits) == 32 else 16
    glyphs.append((codePoint, width, bytes.fromhex(bits)))
glyphs.sort(key=lambda glyph: glyph[0])

blob = bytearray()
for codePoint, width, bitmap in glyphs:
    blob.append(codePoint & 0xFF)
    blob.append((codePoint >> 8) & 0xFF)
    blob.append(width)
    blob += bitmap
raw = bytes(blob)
compressed = zlib.compress(raw, 9)

HEADER = """//
// Source/Core/Rendering/UnifontData.%s — GNU Unifont (BMP plane) glyph bitmaps,
// generated by Scripts/gen-unifont.py. Do not edit.
//
// Input: %s of GNU Unifont %s, SHA-256
// %s.
//
// Font: GNU Unifont (Roman Czyborra, Paul Hardy, et al.), dual-licensed SIL
// Open Font License 1.1 or GPLv2+ with the GNU font-embedding exception. This
// project uses it under the OFL 1.1 (permissive, non-copyleft) — see
// Source/Core/Rendering/UnifontLICENSE.txt. The release names no Reserved Font
// Name.
// Upstream: https://ftp.gnu.org/gnu/unifont/  https://unifoundry.com/
//
// The compressed blob inflates (Codec::Zlib::Inflater) to a stream of records sorted by
// code point: [u16 LE codePoint][u8 width(8|16)][bitmap], where bitmap is
// (width/8 * 16) bytes, 1 bit per pixel, row-major, MSB first.
//
"""


def header(suffix):
    return HEADER % (suffix, inputName, version, inputDigest)


# One byte to a line: the layout clang-format gives a braced list that ends in
# a comma, so the checked-in files are exactly what this script writes.
with open(os.path.join(OUT, "UnifontData.h"), "w", encoding="utf-8") as handle:
    handle.write("// Copyright (C) 2026 Stanislav Yaglo\n")
    handle.write("// SPDX-License-Identifier: Apache-2.0\n\n")
    handle.write(header("h"))
    handle.write("#pragma once\n\nnamespace Ubiquitty::Rendering {\n\n")
    handle.write("constexpr unsigned unifontGlyphCount = %d;\n" % len(glyphs))
    handle.write("constexpr unsigned unifontBlobLength = %d; // inflated bytes\n" % len(raw))
    handle.write("constexpr unsigned unifontCompressedLength = %d;\n" % len(compressed))
    handle.write("extern const unsigned char unifontCompressed[];\n\n")
    handle.write("} // namespace Ubiquitty::Rendering\n")

with open(os.path.join(OUT, "UnifontData.cpp"), "w", encoding="utf-8") as handle:
    handle.write("// Copyright (C) 2026 Stanislav Yaglo\n")
    handle.write("// %s\n" % COPYRIGHT[version])
    handle.write("// SPDX-License-Identifier: Apache-2.0 AND OFL-1.1\n\n")
    handle.write(header("cpp"))
    handle.write('#include "Core/Rendering/UnifontData.h"\n\n')
    handle.write("namespace Ubiquitty::Rendering {\n\n")
    handle.write("const unsigned char unifontCompressed[] = {\n")
    handle.write("".join("    0x%02x,\n" % byte for byte in compressed))
    handle.write("};\n")
    handle.write("\n} // namespace Ubiquitty::Rendering\n")

print("Unifont %s: glyphs=%d raw=%d compressed=%d input-sha256=%s"
      % (version, len(glyphs), len(raw), len(compressed), inputDigest))
