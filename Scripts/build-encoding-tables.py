"""Generate Source/Core/Unicode/Encodings.tables.inc — the byte->Unicode maps
for the legacy (non-UTF-8) input charsets.

The tables enumerate Python's built-in codecs. Their audited reference is
CPython 3.13.15 at 4061bc4c35f7c26f25264666d4ba083b93d2f6f9; codec changes
must be reviewed against Source/Core/Unicode/ENCODINGS-LICENSE.txt before
updating the payload digest. Other interpreters may regenerate the file
only when their complete output matches the audited reference.

Single-byte sets (Latin-1, ISO-8859-15, KOI8-R, CP1252) get a flat
128-entry high-half table (0x80..0xFF -> codepoint, 0xFFFF = unmapped).
0x00..0x7F is ASCII identity, not stored.

Double-byte CJK sets (Shift_JIS, EUC-JP, EUC-KR/CP949, Big5) get a
lead-indexed direct map: a 256-entry lead->row index and rows of 256
codepoints (0 = unmapped), so the decoder indexes twice and branches
never. Single high-byte forms that map (e.g. Shift_JIS half-width
katakana 0xA1..0xDF, EUC-JP 0x8E SS2 kana) are handled in the state
machine, not here.

GB18030's 2-byte plane (the GBK table) is emitted the same way;
its 1-byte (ASCII) and 4-byte ranges are algorithmic in the decoder.

Usage:
  Scripts/build-encoding-tables.py --output Source/Core/Unicode/Encodings.tables.inc
"""

