def single_byte_high(codec):
    """Return list of 128 codepoints for bytes 0x80..0xFF (0xFFFF = unmapped)."""
    out = []
    for b in range(0x80, 0x100):
        try:
            ch = bytes([b]).decode(codec)
            cp = ord(ch)
            out.append(cp if cp <= 0xFFFF else 0xFFFF)
        except (UnicodeDecodeError, ValueError):
            out.append(0xFFFF)
    return out


def double_byte_map(codec, lead_lo, lead_hi, trail_lo, trail_hi,
                    trail_lo2=None, trail_hi2=None):
    """Enumerate every (lead,trail) in range that decodes to one BMP/SMP
    codepoint, returning a sorted list of (packed, cp) where
    packed = lead<<8 | trail."""
    out = {}
    trail_ranges = [(trail_lo, trail_hi)]
    if trail_lo2 is not None:
        trail_ranges.append((trail_lo2, trail_hi2))
    for lead in range(lead_lo, lead_hi + 1):
        for tlo, thi in trail_ranges:
            for trail in range(tlo, thi + 1):
                raw = bytes([lead, trail])
                try:
                    s = raw.decode(codec)
                except UnicodeDecodeError:
                    continue
                # Reject mappings that round-trip through a single-byte form
                # or produce > 1 char (we only key single codepoints here).
                if len(s) != 1:
                    continue
                cp = ord(s)
                out[(lead << 8) | trail] = cp
    return sorted(out.items())


def emit_single(name, arr, f):
    f.write(f"// {name}: bytes 0x80..0xFF -> Unicode (0xFFFF = unmapped).\n")
    f.write(f"static const std::uint16_t {name}[128] = {{\n")
    for i in range(0, 128, 8):
        row = arr[i:i + 8]
        f.write("    " + " ".join(f"0x{c:04X}," for c in row) + "\n")
    f.write("};\n\n")


def gb18030_4byte_bmp_ranges():
    """Coalesce the GB18030 4-byte BMP plane (linear index 0..39419) into
    {linFirst, linLast, cpFirst} runs. Each run is a stretch where the
    codepoint increments in lockstep with the linear index. The decoder
    binary-searches by linear index. The 4-byte SMP plane (U+10000+) is a
    single affine formula handled directly in the decoder."""
    def dec4(idx):
        b1 = idx // (10 * 1260); idx %= (10 * 1260)
        b2 = idx // 1260; idx %= 1260
        b3 = idx // 10; b4 = idx % 10
        return bytes([0x81 + b1, 0x30 + b2, 0x81 + b3, 0x30 + b4])
    runs = []
    start_idx = start_cp = prev_idx = prev_cp = None
    for idx in range(0, 39420):
        try:
            s = dec4(idx).decode("gb18030")
        except UnicodeDecodeError:
            s = None
        cp = ord(s) if (s and len(s) == 1 and ord(s) <= 0xFFFF) else None
        if cp is None:
            if start_idx is not None:
                runs.append((start_idx, prev_idx, start_cp))
                start_idx = None
            continue
        if start_idx is None:
            start_idx = prev_idx = idx
            start_cp = prev_cp = cp
        elif cp == prev_cp + 1 and idx == prev_idx + 1:
            prev_idx, prev_cp = idx, cp
        else:
            runs.append((start_idx, prev_idx, start_cp))
            start_idx = prev_idx = idx
            start_cp = prev_cp = cp
    if start_idx is not None:
        runs.append((start_idx, prev_idx, start_cp))
    return runs


def emit_gb_ranges(name, runs, f):
    f.write(f"// {name}: GB18030 4-byte BMP plane as {{linFirst,linLast,cpFirst}}\n")
    f.write(f"// runs, sorted by linFirst, binary-searched. {len(runs)} runs.\n")
    f.write(f"static const Gb4Range {name}[] = {{\n")
    for a, b, c in runs:
        f.write(f"    {{{a}, {b}, 0x{c:04X}}},\n")
    f.write("};\n")
    f.write(f"static const std::size_t {name}Count = "
            f"sizeof({name}) / sizeof({name}[0]);\n\n")


def emit_double(name, pairs, f):
    """Emit a lead-indexed direct map: lead byte -> row, row -> codepoint.

    The packed keys are contiguous per lead byte, so the sorted array a
    binary search walked was already a two-level index written flat. Written
    as two levels it is two array reads and no branches, which is what the
    single-byte sets have always done — and smaller, because a row holds a
    codepoint per trail byte where an entry held a key beside it.
    """
    by_lead = {}
    for packed, codepoint in pairs:
        by_lead.setdefault(packed >> 8, {})[packed & 0xFF] = codepoint

    leads = sorted(by_lead)
    # Row 0 is the shared empty row every unmapped lead byte points at, so a
    # lead with no mappings costs one index and a zero rather than a branch.
    rows = [[0] * 256]
    lead_to_row = [0] * 256
    for lead in leads:
        lead_to_row[lead] = len(rows)
        row = [0] * 256
        for trail, codepoint in by_lead[lead].items():
            row[trail] = codepoint
        rows.append(row)

    f.write(f"// {name}: lead byte -> row, row[trail] -> Unicode (0 unmapped). "
            f"{len(pairs)} mappings in {len(rows) - 1} rows.\n")
    f.write(f"static const std::uint8_t {name}LeadRow[256] = {{\n")
    for i in range(0, 256, 16):
        f.write("    " + " ".join(f"{v}," for v in lead_to_row[i:i + 16]) + "\n")
    f.write("};\n")
    f.write(f"static const std::uint16_t {name}Rows[{len(rows)}][256] = {{\n")
    for row in rows:
        f.write("    {")
        f.write("".join(f"0x{v:04X}," for v in row))
        f.write("},\n")
    f.write("};\n\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", required=True)
    args = ap.parse_args()

    with io.StringIO() as f:
        f.write("struct DbcsEntry { std::uint16_t key; std::uint16_t cp; };\n")
        f.write("struct Gb4Range { std::uint32_t linFirst; "
                "std::uint32_t linLast; std::uint16_t cpFirst; };\n\n")

        # --- single-byte ---
        emit_single("latin1High", single_byte_high("iso-8859-1"), f)
        emit_single("iso885915High", single_byte_high("iso-8859-15"), f)
        emit_single("koi8rHigh", single_byte_high("koi8-r"), f)
        emit_single("cp1252High", single_byte_high("cp1252"), f)

        # --- Shift_JIS double-byte ---
        # Lead 0x81..0x9F, 0xE0..0xFC; trail 0x40..0x7E, 0x80..0xFC.
        sjis = double_byte_map("shift_jis", 0x81, 0x9F, 0x40, 0x7E, 0x80, 0xFC)
        sjis += double_byte_map("shift_jis", 0xE0, 0xFC, 0x40, 0x7E, 0x80, 0xFC)
        sjis = sorted(dict(sjis).items())
        emit_double("shiftJis", sjis, f)

        # --- EUC-JP double-byte (G1: lead/trail 0xA1..0xFE) ---
        # Plus G3 via 0x8F (3-byte) — handled in the decoder by stripping the
        # 0x8F and looking up the codec on the 3-byte form; we curate G1+G2
        # (G2 0x8E is single-shift kana, in the state machine). For G3 we
        # build a separate 3-byte-keyed map below if present.
        eucjp = double_byte_map("euc-jp", 0xA1, 0xFE, 0xA1, 0xFE)
        emit_double("eucJp", eucjp, f)

        # EUC-JP G3 (JIS X 0212): 0x8F + two bytes 0xA1..0xFE. Key on the
        # trailing two bytes (lead<<8|trail); decoder recognizes the 0x8F
        # prefix and looks here.
        eucjp_g3 = {}
        for lead in range(0xA1, 0xFF):
            for trail in range(0xA1, 0xFF):
                raw = bytes([0x8F, lead, trail])
                try:
                    s = raw.decode("euc-jp")
                except UnicodeDecodeError:
                    continue
                if len(s) == 1:
                    eucjp_g3[(lead << 8) | trail] = ord(s)
        emit_double("eucJpG3", sorted(eucjp_g3.items()), f)

        # --- EUC-KR / CP949 (UHC) double-byte ---
        # CP949 lead 0x81..0xFE, trail 0x41..0x5A,0x61..0x7A,0x81..0xFE.
        cp949 = {}
        for lead in range(0x81, 0xFF):
            for trail in list(range(0x41, 0x5B)) + list(range(0x61, 0x7B)) + \
                    list(range(0x81, 0xFF)):
                raw = bytes([lead, trail])
                try:
                    s = raw.decode("cp949")
                except UnicodeDecodeError:
                    continue
                if len(s) == 1:
                    cp = ord(s)
                    if cp <= 0xFFFF:
                        cp949[(lead << 8) | trail] = cp
        emit_double("cp949", sorted(cp949.items()), f)

        # --- Big5 (incl. HKSCS-free base via Python's 'big5') ---
        # Lead 0x81..0xFE, trail 0x40..0x7E, 0xA1..0xFE.
        big5 = double_byte_map("big5", 0x81, 0xFE, 0x40, 0x7E, 0xA1, 0xFE)
        emit_double("big5", big5, f)

        # --- GB18030 2-byte (GBK) plane ---
        # Lead 0x81..0xFE, trail 0x40..0x7E, 0x80..0xFE. Only BMP here; the
        # 4-byte plane is algorithmic in the decoder.
        gbk = {}
        for lead in range(0x81, 0xFF):
            for trail in list(range(0x40, 0x7F)) + list(range(0x80, 0xFF)):
                raw = bytes([lead, trail])
                try:
                    s = raw.decode("gb18030")
                except UnicodeDecodeError:
                    continue
                if len(s) == 1:
                    cp = ord(s)
                    if cp <= 0xFFFF:
                        gbk[(lead << 8) | trail] = cp
        emit_double("gbk", sorted(gbk.items()), f)

        # --- GB18030 4-byte BMP plane (algorithmic SMP plane in decoder) ---
        gb4 = gb18030_4byte_bmp_ranges()
        emit_gb_ranges("gb4Bmp", gb4, f)
        payload = f.getvalue()

    digest = hashlib.sha256(payload.encode("utf-8")).hexdigest()
    if digest != REFERENCE_PAYLOAD_SHA256:
        sys.exit(
            f"Codec output differs from the audited CPython 3.13.15 reference: {digest}.\n"
            "Output was not written. Use matching codec data, or review the changed "
            "mappings and ENCODINGS-LICENSE.txt before updating REFERENCE_PAYLOAD_SHA256.")
    with open(args.output, "w", encoding="utf-8", newline="\n") as f:
        f.write(TABLE_HEADER)
        f.write(payload)

    # Report sizes to stderr for the curate log.
    sys.stderr.write(
        f"single-byte: 4 x 128\n"
        f"shift_jis: {len(sjis)}  euc-jp: {len(eucjp)} (+g3 {len(eucjp_g3)})  "
        f"cp949: {len(cp949)}  big5: {len(big5)}  gbk: {len(gbk)}\n")


if __name__ == "__main__":
    main()
