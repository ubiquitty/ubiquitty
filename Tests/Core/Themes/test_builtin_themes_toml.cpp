static const int goldenCount = static_cast<int>(sizeof(kGolden) / sizeof(kGolden[0]));

static bool rgbaEq(Ubiquitty::ColorRGBA a, Ubiquitty::ColorRGBA b) { return a.red == b.red && a.green == b.green && a.blue == b.blue && a.alpha == b.alpha; }

int main()
{
    int fails = 0;
    const int n = Ubiquitty::Themes::builtInCount();
    if (n != goldenCount) {
        std::printf("test_builtin_themes_toml: FAIL — built-in count %d != golden %d\n", n, goldenCount);
        return 1;
    }
    for (int i = 0; i < n; ++i) {
        const Ubiquitty::Themes::Theme* t = Ubiquitty::Themes::builtInGet(i);
        if (!t) {
            std::printf("FAIL: builtInGet(%d) is null\n", i);
            ++fails;
            continue;
        }
        const Ubiquitty::Themes::Theme& g = kGolden[i];
        if (!t->name || std::strcmp(t->name, g.name) != 0) {
            std::printf("FAIL: theme %d name '%s' != '%s'\n", i, t->name ? t->name : "(null)", g.name);
            ++fails;
        }
        for (int j = 0; j < 16; ++j)
            if (!rgbaEq(t->ansi[j], g.ansi[j])) {
                std::printf("FAIL: theme %d (%s) ansi[%d] drift\n", i, g.name, j);
                ++fails;
            }
        if (!rgbaEq(t->defaultForeground, g.defaultForeground)) {
            std::printf("FAIL: theme %d (%s) fg drift\n", i, g.name);
            ++fails;
        }
        if (!rgbaEq(t->defaultBackground, g.defaultBackground)) {
            std::printf("FAIL: theme %d (%s) bg drift\n", i, g.name);
            ++fails;
        }
        if (!rgbaEq(t->cursor, g.cursor)) {
            std::printf("FAIL: theme %d (%s) cursor drift\n", i, g.name);
            ++fails;
        }
        if ((t->isDark != 0) != (g.isDark != 0)) {
            std::printf("FAIL: theme %d (%s) isDark %d != %d\n", i, g.name, t->isDark, g.isDark);
            ++fails;
        }
    }
    if (fails != 0) {
        std::printf("test_builtin_themes_toml: FAIL — %d drift(s) from the golden snapshot\n", fails);
        return 1;
    }
    std::printf("test_builtin_themes_toml: %d built-in themes round-trip TOML byte-identical (no color drift)\n", n);
    return 0;
}
