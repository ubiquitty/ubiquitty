"""Render Docs/feature_test_matrix.md from the showcase probe contract.

Each showcase entry maps to its deterministic snapshot/reply coverage. Runtime
pass/fail state belongs to CI; this committed matrix records the executable
contract and is reproducible without a built application.

Stdlib only.

    python3 Tests/Snapshots/gen_matrix.py            # write the table
    python3 Tests/Snapshots/gen_matrix.py --stdout    # print, do not write
    python3 Tests/Snapshots/gen_matrix.py --check     # fail when stale
"""

import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
SHOWCASE = os.path.join(REPO, "Tools", "showcase", "showcase.py")
OUT = os.path.join(REPO, "Docs", "feature_test_matrix.md")


def test_kind(entry):
    if not entry.get("snapshot", True):
        return "reply"
    if entry.get("descriptive"):
        return "page render"
    return "snapshot + reply" if entry["expect"] is not None else "snapshot"


def get_probes():
    out = subprocess.run([sys.executable, SHOWCASE, "--probes"],
                         capture_output=True, text=True, check=True, timeout=10)
    return json.loads(out.stdout)


def md_escape(s):
    return s.replace("|", "\\|")


def main():
    to_stdout = "--stdout" in sys.argv
    check = "--check" in sys.argv
    if to_stdout and check:
        raise SystemExit("--stdout and --check are mutually exclusive")
    probes = get_probes()

    # The generated document carries the project's source header, which the
    # license audit requires of every Markdown file.
    lines = ["<!-- Copyright (C) 2026 Stanislav Yaglo -->",
             "<!-- SPDX-License-Identifier: Apache-2.0 -->",
             ""]
    lines.append("# Feature test matrix")
    lines.append("")
    lines.append("Generated by `Tests/Snapshots/gen_matrix.py` from "
                 "`python3 Tools/showcase/showcase.py --probes`. Each demo section / "
                 "entry is an automated snapshot, a reply check, or both:")
    lines.append("")
    lines.append("- **snapshot** — feed the explicit sequence, or a deterministic "
                 "capture of the composite demo, through `--snapshot` and compare "
                 "the rendered PNG against its baseline.")
    lines.append("- **snapshot + reply** — run the snapshot and also feed the "
                 "sequence through `--probe-reply`, matching the terminal's "
                 "outbound bytes against `expect`.")
    lines.append("- **reply** — the feature draws nothing on the grid, so the entry "
                 "takes no picture and only matches its outbound bytes against "
                 "`expect`.")
    lines.append("- **page render** — the snapshot pins only the page the entry "
                 "draws. What its title names, such as speech, a sound, a desktop "
                 "notification or a rate measured over time, is not in one frame "
                 "and is not asserted here.")
    lines.append("")
    lines.append("**What a row asserts.** A snapshot compares rendered output with its "
                 "checked-in baseline; it detects change but does not independently prove "
                 "correctness. A reply fixture separately checks the specified outbound bytes. "
                 "The [ECMA-35](ecma35_conformance.md) and [ECMA-48](ecma48_conformance.md) "
                 "references describe dispatch and model behavior, not a substitute behavioral "
                 "oracle. Graphics, platform effects, and remote synchronization require their "
                 "own end-to-end tests. This table is a fixture inventory, not a support or "
                 "conformance score.")
    lines.append("")
    lines.append("| Section | Entry | Interactive showcase | Automated contract |")
    lines.append("|---|---|---|---|")

    for p in probes:
        sec, title = p["section"], p["title"]
        kind = test_kind(p)
        lines.append(f"| {md_escape(sec)} | {md_escape(title)} | yes | {kind} |")

    # Roll-up counts.
    from collections import Counter
    kinds = Counter(test_kind(p) for p in probes)
    lines.append("")
    lines.append(f"Totals: {len(probes)} entries — "
                 f"snapshot={kinds['snapshot']}, "
                 f"snapshot + reply={kinds['snapshot + reply']}, "
                 f"reply={kinds['reply']}, "
                 f"page render={kinds['page render']}.")
    lines.append("")

    text = "\n".join(lines)
    if to_stdout:
        print(text)
    elif check:
        if not os.path.exists(OUT):
            raise SystemExit(f"missing generated matrix: {OUT}")
        with open(OUT) as f:
            committed = f.read()
        if committed != text:
            raise SystemExit(
                "feature test matrix is stale; run "
                "python3 Tests/Snapshots/gen_matrix.py")
    else:
        os.makedirs(os.path.dirname(OUT), exist_ok=True)
        with open(OUT, "w") as f:
            f.write(text)
        print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
