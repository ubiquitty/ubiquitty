// 96-set translation. `c` is a position byte already folded into 0xA0..0xFF (a
// 96-set's GR home). characterSetLatin1 is the identity map (byte is the code point);
// characterSetDECSupplemental (DEC-MCS) differs from Latin-1 in ~20 positions:
// Œ, Ÿ, œ and ÿ sit at 0xD7, 0xDD, 0xF7 and 0xFD (xterm
// map_DEC_Supp_Graphic).
// DEC-undefined positions return the byte unchanged.
uint16_t set96Translate(int cs, uint8_t c)
{
    if (cs == characterSetLatin1)
        return c; // identity: 0xA0..0xFF == U+00A0..U+00FF
    if (c < 0xA0)
        return c;
    const std::size_t index = static_cast<std::size_t>(c - 0xA0);
    switch (cs) {
    case characterSetLatin2:
        return isoLatin2RightHalf[index];
    case characterSetGreek:
        return isoGreekRightHalf[index];
    case characterSetHebrew:
        return isoHebrewRightHalf[index];
    case characterSetLatinCyrillic:
        return isoLatinCyrillicRightHalf[index];
    case characterSetLatin5:
        return isoLatin5RightHalf[index];
    default:
        break;
    }
    if (cs != characterSetDECSupplemental)
        return c;
    switch (c) {
    case 0xA0:
        return 0x00A0; // (DEC: undefined) NBSP
    case 0xA1:
        return 0x00A1; // ¡
    case 0xA2:
        return 0x00A2; // ¢
    case 0xA3:
        return 0x00A3; // £
    case 0xA4:
        return c; // DEC: undefined
    case 0xA5:
        return 0x00A5; // ¥
    case 0xA6:
        return c; // DEC: undefined
    case 0xA7:
        return 0x00A7; // §
    case 0xA8:
        return 0x00A4; // ¤ (DEC swaps ¤ here)
    case 0xA9:
        return 0x00A9; // ©
    case 0xAA:
        return 0x00AA; // ª
    case 0xAB:
        return 0x00AB; // «
    case 0xAC:
    case 0xAD:
    case 0xAE:
    case 0xAF:
        return c; // DEC: undefined
    case 0xB0:
        return 0x00B0; // °
    case 0xB1:
        return 0x00B1; // ±
    case 0xB2:
        return 0x00B2; // ²
    case 0xB3:
        return 0x00B3; // ³
    case 0xB4:
        return c; // DEC: undefined
    case 0xB5:
        return 0x00B5; // µ
    case 0xB6:
        return 0x00B6; // ¶
    case 0xB7:
        return 0x00B7; // ·
    case 0xB8:
        return c; // DEC: undefined
    case 0xB9:
        return 0x00B9; // ¹
    case 0xBA:
        return 0x00BA; // º
    case 0xBB:
        return 0x00BB; // »
    case 0xBC:
        return 0x00BC; // ¼
    case 0xBD:
        return 0x00BD; // ½
    case 0xBE:
        return c; // DEC: undefined
    case 0xBF:
        return 0x00BF; // ¿
    case 0xC0:
    case 0xC1:
    case 0xC2:
    case 0xC3:
    case 0xC4:
    case 0xC5:
        return c - 0xC0 + 0x00C0; // À Á Â Ã Ä Å — identical to Latin-1
    case 0xC6:
        return 0x00C6; // Æ
    case 0xC7:
    case 0xC8:
    case 0xC9:
    case 0xCA:
    case 0xCB:
    case 0xCC:
    case 0xCD:
    case 0xCE:
    case 0xCF:
        return c - 0xC7 + 0x00C7; // Ç È É Ê Ë Ì Í Î Ï
    case 0xD0:
        return c; // DEC: undefined (Latin-1 Ð)
    case 0xD1:
    case 0xD2:
    case 0xD3:
    case 0xD4:
    case 0xD5:
    case 0xD6:
        return c - 0xD1 + 0x00D1; // Ñ Ò Ó Ô Õ Ö
    case 0xD7:
        return 0x0152; // Œ (DEC: not ×)
    case 0xD8:
    case 0xD9:
    case 0xDA:
    case 0xDB:
    case 0xDC:
        return c - 0xD8 + 0x00D8; // Ø Ù Ú Û Ü
    case 0xDD:
        return 0x0178; // Ÿ (DEC: not Ý)
    case 0xDE:
        return c; // DEC: undefined (Latin-1 Þ)
    case 0xDF:
        return 0x00DF; // ß
    case 0xE0:
    case 0xE1:
    case 0xE2:
    case 0xE3:
    case 0xE4:
    case 0xE5:
        return c - 0xE0 + 0x00E0; // à á â ã ä å
    case 0xE6:
        return 0x00E6; // æ
    case 0xE7:
    case 0xE8:
    case 0xE9:
    case 0xEA:
    case 0xEB:
    case 0xEC:
    case 0xED:
    case 0xEE:
    case 0xEF:
        return c - 0xE7 + 0x00E7; // ç è é ê ë ì í î ï
    case 0xF0:
        return c; // DEC: undefined (Latin-1 ð)
    case 0xF1:
    case 0xF2:
    case 0xF3:
    case 0xF4:
    case 0xF5:
    case 0xF6:
        return c - 0xF1 + 0x00F1; // ñ ò ó ô õ ö
    case 0xF7:
        return 0x0153; // œ (DEC: not ÷)
    case 0xF8:
    case 0xF9:
    case 0xFA:
    case 0xFB:
    case 0xFC:
        return c - 0xF8 + 0x00F8; // ø ù ú û ü
    case 0xFD:
        return 0x00FF; // ÿ (DEC: not ý)
    case 0xFE:
        return c; // DEC: undefined (Latin-1 þ)
    case 0xFF:
        return c; // DEC: undefined (Latin-1 ÿ)
    default:
        return c;
    }
}

