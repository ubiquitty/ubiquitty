// DEC special-graphics translation to canonical Unicode (U+2500 block
// + U+00B0 / U+00B1). Cells always hold Unicode; frontends fold at paint.
uint16_t decSpecialToUnicode(uint8_t c)
{
    switch (c) {
    case '`':
        return 0x25C6; // ◆
    case 'a':
        return 0x2592; // ▒
    case 'b':
        return 0x2409; // HT visualisation
    case 'c':
        return 0x240C; // FF
    case 'd':
        return 0x240D; // CR
    case 'e':
        return 0x240A; // LF
    case 'f':
        return 0x00B0; // °
    case 'g':
        return 0x00B1; // ±
    case 'h':
        return 0x2424; // NL
    case 'i':
        return 0x240B; // VT
    case 'j':
        return 0x2518; // ┘
    case 'k':
        return 0x2510; // ┐
    case 'l':
        return 0x250C; // ┌
    case 'm':
        return 0x2514; // └
    case 'n':
        return 0x253C; // ┼
    case 'o':
        return 0x23BA; // scan 1
    case 'p':
        return 0x23BB; // scan 3
    case 'q':
        return 0x2500; // ─
    case 'r':
        return 0x23BC; // scan 7
    case 's':
        return 0x23BD; // scan 9
    case 't':
        return 0x251C; // ├
    case 'u':
        return 0x2524; // ┤
    case 'v':
        return 0x2534; // ┴
    case 'w':
        return 0x252C; // ┬
    case 'x':
        return 0x2502; // │
    case 'y':
        return 0x2264; // ≤
    case 'z':
        return 0x2265; // ≥
    case '{':
        return 0x03C0; // π
    case '|':
        return 0x2260; // ≠
    case '}':
        return 0x00A3; // £
    case '~':
        return 0x00B7; // ·
    default:
        return c;
    }
}

// DEC Technical Character Set (VT330/VT340 Programmer Reference; designated
// `ESC ( >` plus the G1..G3 forms) → canonical Unicode, indexed by position -
// 0x21. A table, not a switch: 85 of the 94 positions map one-to-one, with
// nothing to fold into case ranges. The nine positions DEC leaves unassigned
// (`-` in the row comments) resolve to SPACE rather than the raw byte — a hard
// set blanks its undefined positions, and this one sits in GL, where passing
// the byte through would print an unrelated ASCII glyph. The five Sigma-building
// pieces at 0x33..0x37 have no dedicated Unicode character and take the nearest
// encoded shape; every other position has an exact one.
uint16_t decTechnicalToUnicode(uint8_t c)
{
    static constexpr uint16_t table[94] = {
        0x23B7, 0x250C, 0x2500, 0x2320, 0x2321, 0x2502, 0x23A1, 0x23A3, // 0x21 ⎷ ┌ ─ ⌠ ⌡ │ ⎡ ⎣
        0x23A4, 0x23A6, 0x239B, 0x239D, 0x239E, 0x23A0, 0x23A8, 0x23AC, // 0x29 ⎤ ⎦ ⎛ ⎝ ⎞ ⎠ ⎨ ⎬
        0x23B2, 0x23B3, 0x2572, 0x2571, 0x231D, 0x231F, 0x27E9, 0x0020, // 0x31 ⎲ ⎳ ╲ ╱ ⌝ ⌟ ⟩ -
        0x0020, 0x0020, 0x0020, 0x2264, 0x2260, 0x2265, 0x222B, 0x2234, // 0x39 - - - ≤ ≠ ≥ ∫ ∴
        0x221D, 0x221E, 0x00F7, 0x0394, 0x2207, 0x03A6, 0x0393, 0x223C, // 0x41 ∝ ∞ ÷ Δ ∇ Φ Γ ∼
        0x2243, 0x0398, 0x00D7, 0x039B, 0x21D4, 0x21D2, 0x2261, 0x03A0, // 0x49 ≃ Θ × Λ ⇔ ⇒ ≡ Π
        0x03A8, 0x0020, 0x03A3, 0x0020, 0x0020, 0x221A, 0x03A9, 0x039E, // 0x51 Ψ - Σ - - √ Ω Ξ
        0x03A5, 0x2282, 0x2283, 0x2229, 0x222A, 0x2227, 0x2228, 0x00AC, // 0x59 Υ ⊂ ⊃ ∩ ∪ ∧ ∨ ¬
        0x03B1, 0x03B2, 0x03C7, 0x03B4, 0x03B5, 0x03C6, 0x03B3, 0x03B7, // 0x61 α β χ δ ε φ γ η
        0x03B9, 0x03B8, 0x03BA, 0x03BB, 0x0020, 0x03BD, 0x2202, 0x03C0, // 0x69 ι θ κ λ - ν ∂ π
        0x03C8, 0x03C1, 0x03C3, 0x03C4, 0x0020, 0x0192, 0x03C9, 0x03BE, // 0x71 ψ ρ σ τ - ƒ ω ξ
        0x03C5, 0x03B6, 0x2190, 0x2191, 0x2192, 0x2193 // 0x79 υ ζ ← ↑ → ↓
    };
    if (c < 0x21 || c > 0x7E)
        return c; // 02/00 SPACE and 07/15 DEL fall outside a 94-set
    return table[c - 0x21];
}

