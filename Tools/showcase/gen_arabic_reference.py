"""authoring-only one-shot generator (not imported at runtime).

Renders correctly-shaped, right-to-left Arabic with PIL's raqm layout engine
(cursive joining + lam-alef ligatures + BiDi) and serializes the raw RGBA as a
zlib+base64 blob into Tools/showcase/assets/arabic_reference.py. The showcase then shows
that static image as a "this is what shaped Arabic should look like" reference
without needing PIL/raqm at runtime.

Run once on a machine with PIL+raqm and an Arabic system font:

    python3 Tools/showcase/gen_arabic_reference.py

Requires: Pillow built with raqm (PIL.features.check('raqm') is True).
"""

import base64
import os
import zlib

from PIL import Image, ImageDraw, ImageFont, features

# Showcase Theme: bg (16,18,26), text (208,214,228). Render the reference on the
# showcase bg with the showcase text color so it sits with no visible edge beside the live
# row.
BG = (16, 18, 26, 255)
FG = (208, 214, 228, 255)

# Strings to render. Each exercises Arabic cursive shaping; the first is the
# exact string from the fonts fallback row so the reference matches it 1:1.
STRINGS = [
    "العربية مرحبا",   # the fallback row string
    "سلام",            # seen-lam-alef-meem: joining + lam-alef ligature
    "لا",              # lam-alef isolated ligature
    "بسم",             # beh-seen-meem: initial / medial / final forms
]

FONT_CANDIDATES = [
    "/System/Library/Fonts/Supplemental/SFArabic.ttf",
    "/System/Library/Fonts/Supplemental/GeezaPro.ttc",
    "/System/Library/Fonts/SFArabic.ttf",
    "/System/Library/Fonts/GeezaPro.ttc",
]

SIZE = 30          # ~cell-height multiple, renders cleanly
PAD = 8
GAP = 10           # vertical gap between the stacked strings

ASSET = os.path.join(os.path.dirname(__file__), "assets", "arabic_reference.py")


def _font_path():
    for p in FONT_CANDIDATES:
        if os.path.exists(p):
            return p
    raise SystemExit("no Arabic system font found among: " + ", ".join(FONT_CANDIDATES))


def main():
    if not features.check("raqm"):
        raise SystemExit("PIL raqm layout engine unavailable; cannot shape Arabic")

    font_path = _font_path()
    font = ImageFont.truetype(font_path, SIZE, layout_engine=ImageFont.Layout.RAQM)

    # Measure each line (raqm-laid-out) to size the canvas.
    probe = Image.new("RGBA", (4, 4), BG)
    pd = ImageDraw.Draw(probe)
    lines = []
    max_w = 0
    for s in STRINGS:
        box = pd.textbbox((0, 0), s, font=font, direction="rtl")
        w = box[2] - box[0]
        h = box[3] - box[1]
        lines.append((s, w, h, box))
        max_w = max(max_w, w)

    line_h = SIZE + 6
    width = max_w + 2 * PAD
    height = 2 * PAD + len(lines) * line_h + (len(lines) - 1) * GAP

    img = Image.new("RGBA", (width, height), BG)
    draw = ImageDraw.Draw(img)
    y = PAD
    for s, w, h, box in lines:
        # Right-align each RTL string within the canvas.
        x = width - PAD - w
        draw.text((x, y), s, font=font, fill=FG, direction="rtl")
        y += line_h + GAP

    rgba = img.tobytes()
    assert len(rgba) == width * height * 4

    blob = base64.b64encode(zlib.compress(rgba, 9)).decode("ascii")
    # Chunk the base64 so the committed module has readable line lengths.
    chunks = [blob[i:i + 76] for i in range(0, len(blob), 76)]
    b64_literal = "\n".join('    "%s"' % c for c in chunks)

    os.makedirs(os.path.dirname(ASSET), exist_ok=True)
    with open(ASSET, "w") as f:
        f.write(_TEMPLATE.format(
            font=os.path.basename(font_path),
            strings=", ".join(repr(s) for s in STRINGS),
            width=width,
            height=height,
            b64=b64_literal,
        ))

    print("wrote %s  (%dx%d, %d bytes raw, %d bytes blob)"
          % (ASSET, width, height, len(rgba), len(blob)))


_TEMPLATE = '''\
"""Static reference image of CORRECTLY-SHAPED Arabic (authoring-time output).

Generated by Tools/showcase/gen_arabic_reference.py with PIL's raqm layout engine, which
does proper Arabic cursive joining, lam-alef ligatures, and BiDi. The pixels
are baked in here as a zlib+base64 RGBA blob so the showcase can display the
correctly-shaped result with no PIL/raqm runtime dependency (zlib+base64 are
stdlib). Do not hand-edit; regenerate with the generator instead.

Font: {font}
Strings (top to bottom, each shaped RTL): {strings}

Decoded module API:
    WIDTH, HEIGHT : int
    RGBA          : bytes  (len == WIDTH * HEIGHT * 4, top-to-bottom rows)
"""

import base64
import zlib

WIDTH = {width}
HEIGHT = {height}

_BLOB = (
{b64}
)

RGBA = zlib.decompress(base64.b64decode(_BLOB))

assert len(RGBA) == WIDTH * HEIGHT * 4, "arabic_reference: RGBA size mismatch"
'''


if __name__ == "__main__":
    main()
